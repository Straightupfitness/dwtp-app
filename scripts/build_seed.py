"""Build supabase/seed/0002_circles.sql from the Capacity Circles design doc (doc 23, Section 11).

Usage: python3 scripts/build_seed.py path/to/DWTP_Circle_System_Design.md
Re-run whenever the design doc changes; the output is plain INSERTs.
"""
import re
import sys
import uuid

DOC = open(sys.argv[1], encoding="utf-8").read()
NS = uuid.UUID("6f1c2b8e-1d2a-4c55-9a2e-0d7d3f6c9b11")

CIRCLES = [
    # heading in doc, slug, name, kind, method_part
    ("### 11.1 Circadian Reset", "circadian-reset", "Circadian Reset", "growth", "circadian_reset"),
    ("### 11.2 Food Quality", "food-quality", "Food Quality", "growth", "metabolism_fix"),
    ("### 11.3 Food Philosophy", "food-philosophy", "Food Philosophy", "growth", "metabolism_fix"),
    ("### 11.4 Kitchen", "kitchen", "Kitchen", "growth", "metabolism_fix"),
    ("### 11.5 Supplements", "supplements", "Supplements", "growth", "metabolism_fix"),
    ("### 11.6 Strength", "strength", "Strength", "growth", "proper_strength_training"),
    ("### 11.7 Cardio", "cardio", "Cardio", "growth", "proper_strength_training"),
    ("### 11.8 Mobility & Desk Body", "mobility", "Mobility & Desk Body", "growth", "proper_strength_training"),
    ("### 11.9 Mindset", "mindset", "Mindset", "growth", "lifestyle"),
    ("### 11.10 Healthy Home", "healthy-home", "Healthy Home", "growth", "lifestyle"),
    ("### 11.11 Role Model", "role-model", "Role Model", "growth", "lifestyle"),
    ("#### Travel (event)", "travel", "Travel", "fixit_event", None),
    ("#### Holidays & Events (event)", "holidays-events", "Holidays & Events", "fixit_event", None),
    ("#### Menopause Symptoms (ongoing)", "menopause", "Menopause Symptoms", "fixit_ongoing", None),
    ("#### Knees (ongoing)", "knees", "Knees", "fixit_ongoing", None),
    ("#### Shoulder Pain (ongoing)", "shoulder", "Shoulder Pain", "fixit_ongoing", None),
    ("#### Plantar Fasciitis (ongoing)", "plantar-fasciitis", "Plantar Fasciitis", "fixit_ongoing", None),
    ("#### Hip Imbalances (ongoing)", "hips", "Hip Imbalances", "fixit_ongoing", None),
]

TYPE_RE = re.compile(r"^(Do|Eat|Take|Get|Learn|Hit)\b\s*(\([^)]*\)|daily)?\s*:\s*", re.I)


def q(s):
    return "null" if s is None else "'" + s.replace("'", "''") + "'"


def clean(s):
    s = re.sub(r"\*\*|`", "", s)
    s = re.sub(r"_\((also [^)]*)\)_", r"(\1)", s)
    s = re.sub(r"_([^_]+)_", r"\1", s)
    return re.sub(r"\s+", " ", s).strip()


def section(heading, nxt):
    a = DOC.index(heading)
    ends = [DOC.find(h, a + 1) for h in nxt if DOC.find(h, a + 1) > 0]
    ends.append(DOC.find("\n### ", a + 1) if heading.startswith("####") else DOC.find("\n### ", a + 1))
    ends = [e for e in ends if e > 0]
    return DOC[a:min(ends)] if ends else DOC[a:]


def split_items(cell):
    out, cur_type, cur_cad = [], "do", "daily"
    for part in [p.strip() for p in re.split(r"\s·\s", cell) if p.strip()]:
        m = TYPE_RE.match(part)
        if m:
            cur_type = m.group(1).lower()
            mod = (m.group(2) or "").lower()
            cur_cad = "weekly" if ("week" in mod or "2x" in mod or "every" in mod) else "daily"
            if cur_type in ("get", "learn", "hit"):
                cur_cad = "once"
            part = part[m.end():]
        elif part.lower().startswith("tip:"):
            continue
        text = clean(part)
        if not text or text == "—":
            continue
        title, detail = text, None
        pm = re.match(r"^(.{3,80}?)\s*\((.+)\)\s*$", text)
        if pm:
            title, detail = pm.group(1).strip(), pm.group(2).strip()
        title = title[:1].upper() + title[1:]
        out.append((cur_type, cur_cad, title[:200], detail))
    return out


headings = [c[0] for c in CIRCLES]
sql = ["-- Generated by scripts/build_seed.py from doc 23 (Capacity Circles). Do not edit by hand.",
       "begin;", "delete from public.circles;"]
for i, (h, slug, name, kind, part) in enumerate(CIRCLES):
    body = section(h, headings[i + 1:])
    cid = uuid.uuid5(NS, slug)
    goal = None
    gm = re.search(r"\*\*Goal of the circle:\*\*\s*(.+)", body)
    if gm:
        goal = clean(gm.group(1))
    ref = re.search(r"\*\*See (?:a |her )?(?:doctor|physio[^*]*)[^*]*\*\*\s*(.+)", body)
    sql.append(f"insert into public.circles (id, slug, name, kind, method_part, goal, see_a_professional, sort) values "
               f"({q(str(cid))}, {q(slug)}, {q(name)}, {q(kind)}, {q(part)}, {q(goal)}, {q(clean(ref.group(1)) if ref else None)}, {i});")
    for line in body.splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) < 3 or not re.match(r"^\*\*\d+\*\*$", cells[0]):
            continue
        num = int(cells[0].strip("*"))
        rname = clean(cells[1])
        if len(cells) >= 4:
            outcome, items_cell = clean(cells[2]), cells[3]
        else:
            outcome, items_cell = None, cells[2]
        if slug == "supplements":  # Ring | Name | Items
            outcome, items_cell = None, cells[2]
        rid = uuid.uuid5(NS, f"{slug}:{num}")
        sql.append(f"insert into public.rings (id, circle_id, ring_number, name, outcome) values "
                   f"({q(str(rid))}, {q(str(cid))}, {num}, {q(rname)}, {q(outcome)});")
        for j, (t, cad, title, detail) in enumerate(split_items(items_cell)):
            sql.append(f"insert into public.ring_items (ring_id, item_type, cadence, title, detail, sort) values "
                       f"({q(str(rid))}, {q(t)}, {q(cad)}, {q(title)}, {q(detail)}, {j});")
sql.append("commit;")
open("supabase/seed/0002_circles.sql", "w", encoding="utf-8").write("\n".join(sql) + "\n")
print("rings:", sum(1 for s in sql if s.startswith("insert into public.rings")),
      "items:", sum(1 for s in sql if s.startswith("insert into public.ring_items")))
