"""Builds supabase/migrations/0024_programs.sql: the programs table, each client's workout program, and Michael's other
Trainerize programs (read October 28, 2026; Quarantine Crusher 2.0 left out as outdated, the "Copy" duplicate left out).

Everyone stays on the main program ('sltp', shown as the Driven Woman Transformation Program). Michael picks another
program per client in Coach -> client -> Edit details.

How Trainerize phases become weeks in the app:
- A phase with up to 5 strength workouts repeats them every week of the phase (Day 1, Day 2, ...).
- A phase with more (13 Hard & Resilient: 48 workouts over 12 weeks) runs them in order: 4 a week (or 3, 5, 2, 6,
  whichever divides evenly), each block for an equal share of the phase's weeks.
- "Day 1a / 1b / 1c / 1d" run in weeks 1 / 2 / 3 / 4 of the phase.
- When a phase holds its own workouts plus the Straight-Up Bodyweight days, only its own are used (Straight-Up
  Bodyweight is a program of its own).
- Info videos (meal plan, recipes, questions answered) are left out; they live in Lessons.
"""
import json, math, re
from pathlib import Path

ROOT = Path(__file__).resolve().parent
d = json.loads((ROOT / "data/trainerize_programs.json").read_text())
new_clips = set(json.loads((ROOT / "data/programs_clips.json").read_text()))
W, E = d["workouts"], d["exercises"]
q = lambda s: "null" if s is None or s == "" else "'" + str(s).replace("'", "''") + "'"
n = lambda v: "null" if v in (None, "") else str(v)

NAMES = {2760057: "Driven Woman (old Trainerize draft)"}  # so it isn't confused with the main program
INFO = re.compile(r"questions|meal plan|recipe|essentials", re.I)
is_workout = lambda name: bool(re.match(r"[A-Za-z0-9]", name)) and not INFO.search(name)
is_cardio = lambda name: "Cardio" in name

out = ["-- Workout programs (decided October 28). Generated by scripts/build_programs.py. Safe to run more than once.", "", """
create table if not exists public.programs (
  id text primary key,                   -- 'sltp' (the main program) or 'tz-<Trainerize id>'
  name text not null,
  description text,
  weeks int not null default 0,
  sort int not null default 100,
  active boolean not null default true   -- shown in the coach's program list
);
alter table public.programs enable row level security;
drop policy if exists "read" on public.programs;
create policy "read" on public.programs for select using (auth.uid() is not null);
drop policy if exists "coach writes" on public.programs;
create policy "coach writes" on public.programs for all using (public.is_coach()) with check (public.is_coach());

insert into public.programs (id, name, description, weeks, sort) values
  ('sltp', 'Driven Woman Transformation Program', 'The main program: Driven Woman, Strong Life, Photo Shoot Ready, Strong Life Forever.',
   (select coalesce(sum(weeks), 0) from public.program_phases where program = 'sltp'), 0)
  on conflict (id) do update set weeks = excluded.weeks;

-- Her workout program, and the week of it she starts on (Week 1 unless Michael sets it).
alter table public.profiles add column if not exists workout_program text not null default 'sltp';
alter table public.profiles add column if not exists workout_start_week int not null default 1;

-- Workouts that run only in some weeks of a phase (week of the phase; null = every week).
alter table public.phase_workouts add column if not exists from_week int;
alter table public.phase_workouts add column if not exists to_week int;
""".strip(), ""]

used_w, used_e = set(), set()
progs = []
for sort, p in enumerate(sorted(d["programs"], key=lambda p: p["name"].lower()), 1):
    pid = f"tz-{p['id']}"
    phases = []
    week = 1
    for pos, ph in enumerate(p["phases"], 1):
        weeks = max(1, math.ceil(ph["days"] / 7))
        names = {w: W[str(w)]["name"].strip() for w in ph["workouts"]}
        strength = [w for w in ph["workouts"] if is_workout(names[w]) and not is_cardio(names[w])]
        cardio = [w for w in ph["workouts"] if is_workout(names[w]) and is_cardio(names[w])]
        own = [w for w in strength if not names[w].startswith("SUBodyweight")]
        if own and len(own) < len(strength): strength = own
        links = []  # (workout, day, from_week, to_week)
        letters = {w: re.search(r"Day\s*0*(\d+)([a-d])$", names[w]) for w in strength}
        if any(letters.values()):
            for i, w in enumerate(strength, 1):
                m = letters[w] or re.search(r"Day\s*0*(\d+)", names[w])
                day = int(m.group(1)) if m else i
                wk = "abcd".index(m.group(2)) + 1 if letters[w] else None
                links.append((w, day, wk, wk))
        elif len(strength) <= 5:
            days = []
            for i, w in enumerate(strength, 1):
                m = re.search(r"Day\s*0*(\d+)", names[w]) or re.search(r"P\d+D(\d+)", names[w])
                days.append(int(m.group(1)) if m else i)
            if len(set(days)) < len(days) or max(days, default=0) > len(days): days = list(range(1, len(strength) + 1))
            links = [(w, dd, None, None) for w, dd in zip(strength, days)]
        else:
            N = len(strength)
            per = next((k for k in (4, 3, 5, 2, 6) if N % k == 0 and weeks % (N // k) == 0), None)
            if per is None: raise SystemExit(f"can't lay out {p['name']} / {ph['name']}: {N} workouts in {weeks} weeks")
            span = weeks // (N // per)
            for i, w in enumerate(strength):
                b = i // per
                links.append((w, i % per + 1, b * span + 1, (b + 1) * span))
        links += [(w, None, None, None) for w in cardio]
        phases.append(dict(id=ph["id"], pos=pos, name=ph["name"].strip(), weeks=weeks, first=week, links=links,
                           kind="deload" if re.search("deload", ph["name"], re.I) else "pivot" if "Pivot" in ph["name"] else "max" if "Max" in ph["name"] else "build"))
        week += weeks
        for l in links: used_w.add(l[0])
    count = sum(len(x["links"]) for x in phases)
    progs.append(dict(id=pid, name=NAMES.get(p["id"], p["name"].strip()), desc=(p.get("description") or "").strip(), weeks=week - 1, sort=sort, active=count > 0, phases=phases))

for w in used_w:
    for x in W[str(w)]["exercises"]: used_e.add(x["ex"])
have = set(json.loads((ROOT / "data/sltp_trainerize.json").read_text())["exercises"])  # already in the app (0023)
used_e = {e for e in used_e if str(e) not in have or e in new_clips}

out.append("-- Exercises (new ones; ones already in the app keep their saved clip).")
for k in sorted(used_e):
    e = E[str(k)]
    v = e.get("video") or ""
    yt = v if v and ":" not in v else None
    clip = f"sltp/{k}" if k in new_clips else None
    out.append(f"insert into public.exercises (id, name, notes, youtube_id, clip_path) values ({k}, {q(e['name'].strip())}, {q((e.get('description') or '').strip())}, {q(yt)}, {q(clip)}) "
               "on conflict (id) do update set name = excluded.name, notes = excluded.notes, youtube_id = coalesce(excluded.youtube_id, public.exercises.youtube_id), clip_path = coalesce(public.exercises.clip_path, excluded.clip_path), updated_at = now();")
def workout_sql(k):
    w = W[str(k)]
    kind = "cardio" if is_cardio(w["name"]) else "strength"
    mins = round(w["duration"] / 60) if w.get("duration") else None
    lines = [f"insert into public.workouts (id, name, kind, circuit, rounds, minutes, notes) values ({k}, {q(w['name'].strip())}, '{kind}', {str(w['type'] == 'workoutCircuit').lower()}, {n(w.get('rounds'))}, {n(mins)}, {q(w.get('instruction'))}) "
             "on conflict (id) do update set name = excluded.name, kind = excluded.kind, circuit = excluded.circuit, rounds = excluded.rounds, minutes = excluded.minutes, notes = excluded.notes;",
             f"delete from public.workout_items where workout_id = {k};"]
    rows = []
    for i, x in enumerate(w["exercises"], 1):
        td = x.get("td") or {}
        rows.append(f"({k}, {i}, {x['ex']}, {x['sets'] or 1}, {q(x['target'])}, {n(td.get('time'))}, {n(x['rest'] or None)}, {q(x['rec'])})")
    if rows:
        lines.append("insert into public.workout_items (workout_id, position, exercise_id, sets, target, seconds, rest_seconds, log_type) values\n  " + ",\n  ".join(rows) + ";")
    return lines

blocks, done = [], set()
for p in progs:
    b = [f"\n-- {p['name']}"]
    for ph in p["phases"]:
        for w, *_ in ph["links"]:
            if w not in done: done.add(w); b += workout_sql(w)
    b.append(f"insert into public.programs (id, name, description, weeks, sort, active) values ({q(p['id'])}, {q(p['name'])}, {q(p['desc'])}, {p['weeks']}, {p['sort']}, {str(p['active']).lower()}) "
             "on conflict (id) do update set name = excluded.name, description = excluded.description, weeks = excluded.weeks, sort = excluded.sort, active = excluded.active;")
    for ph in p["phases"]:
        b.append(f"insert into public.program_phases (id, program, position, name, stage, kind, weeks, first_week) values ({ph['id']}, {q(p['id'])}, {ph['pos']}, {q(ph['name'])}, 'CUSTOM', '{ph['kind']}', {ph['weeks']}, {ph['first']}) "
                 "on conflict (id) do update set program = excluded.program, position = excluded.position, name = excluded.name, stage = excluded.stage, kind = excluded.kind, weeks = excluded.weeks, first_week = excluded.first_week;")
        b.append(f"delete from public.phase_workouts where phase_id = {ph['id']};")
        if ph["links"]:
            b.append("insert into public.phase_workouts (phase_id, workout_id, day, from_week, to_week) values " +
                     ", ".join(f"({ph['id']}, {w}, {n(day)}, {n(a)}, {n(c)})" for w, day, a, c in ph["links"]) + " on conflict do nothing;")
    blocks.append(b)

# The SQL editor takes about half a megabyte at a time, so the programs go in parts, run in order.
LIMIT = 420_000
parts, cur = [out], out
for b in blocks:
    if sum(len(l) + 1 for l in cur) + sum(len(l) + 1 for l in b) > LIMIT:
        cur = [f"-- Workout programs, part {len(parts) + 1}. Run after part {len(parts)}. Generated by scripts/build_programs.py. Safe to run more than once."]
        parts.append(cur)
    cur += b
cur.append(f"\n-- {len(progs)} programs, {len(used_w)} workouts, {len(used_e)} new exercises.")
cur.append("select (select count(*) from public.programs) programs, (select count(*) from public.programs where active) with_workouts, (select count(*) from public.workouts) workouts, (select count(*) from public.exercises) exercises;")
for old in (ROOT.parent / "supabase/migrations").glob("0024_programs*.sql"): old.unlink()
for i, part in enumerate(parts, 1):
    f = ROOT.parent / f"supabase/migrations/0024_programs{'' if i == 1 else f'_part{i}'}.sql"
    f.write_text("\n".join(part) + "\n")
    print(f.name, sum(len(l) + 1 for l in part))
for p in progs:
    print(f"{p['name'][:45]:45} {p['weeks']:3}w {sum(len(x['links']) for x in p['phases']):4} links {'' if p['active'] else '(no workouts, hidden)'}")
print("workouts", len(used_w), "new exercises", len(used_e))
