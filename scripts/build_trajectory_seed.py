"""Build supabase/seed/02_trajectory.sql from the 26-week Main Trajectory (doc 27, Section 3).
Usage: python3 scripts/build_trajectory_seed.py path/to/DWTP_26_Week_Main_Trajectory.md
"""
import re, sys, uuid
NS = uuid.UUID("6f1c2b8e-1d2a-4c55-9a2e-0d7d3f6c9b11")
DOC = open(sys.argv[1], encoding="utf-8").read()
SLUG = {"Circadian Reset": "circadian-reset", "Food Quality": "food-quality", "Food Philosophy": "food-philosophy",
        "Kitchen": "kitchen", "Supplements": "supplements", "Strength": "strength", "Cardio": "cardio",
        "Mobility": "mobility", "Mindset": "mindset", "Healthy Home": "healthy-home", "Role Model": "role-model"}
VIDEO_WEEKS = {4, 8, 12, 16, 20, 26}
out = ["-- Generated by scripts/build_trajectory_seed.py from doc 27. Do not edit by hand.", "begin;",
       "delete from public.trajectory_weeks;"]
for line in DOC.splitlines():
    c = [x.strip() for x in line.strip().strip("|").split("|")]
    if len(c) < 7 or not c[0].isdigit():
        continue
    wk, phase, habits, checkin, moments = int(c[0]), c[1].lower(), c[2], c[5].lower(), c[6].lower()
    ctype = ("week1" if wk == 1 else "results" if wk == 26 else "milestone" if wk == 12 else "halfway" if wk == 13
             else "last_chance" if wk == 24 else "four_week" if "4-week" in checkin else "standard")
    diet = habits.lower().startswith("**diet break**")
    tags = [t for t, k in (("upsell_1", "upsell 1"), ("upsell_2", "upsell 2"), ("upsell_3", "upsell 3"),
                           ("sleep_better_checkpoint", "sleep better"), ("last_chance", "last chance"),
                           ("guarantee_15lb", "15 pound"), ("onboarding_call", "onboarding")) if k in moments]
    out.append(f"insert into public.trajectory_weeks (week_number, phase, checkin_type, checkin_is_video, is_diet_break, moments) "
               f"values ({wk}, '{phase}', '{ctype}', {str(wk in VIDEO_WEEKS).lower()}, {str(diet).lower()}, "
               f"'{{{','.join(tags)}}}');")
    for name, slug in SLUG.items():
        for m in re.finditer(re.escape(name) + r" (\d+)\b", habits):
            rid = uuid.uuid5(NS, f"{slug}:{int(m.group(1))}")
            out.append(f"insert into public.trajectory_week_rings (week_number, ring_id) values ({wk}, '{rid}') on conflict do nothing;")
out.append("commit;")
open("supabase/seed/02_trajectory.sql", "w", encoding="utf-8").write("\n".join(out) + "\n")
print("weeks:", sum(1 for l in out if "trajectory_weeks (" in l), "week-rings:", sum(1 for l in out if "week_rings" in l))
