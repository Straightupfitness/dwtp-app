"""Builds supabase/migrations/0013_lessons.sql from doc 20 (the Xperiencify content library export).

Usage: python3 scripts/build_lessons.py path/to/doc20.md

- Strong Body Wednesday 1-52: title, YouTube video, notes (or the email text when there are no notes).
- Strong Mind Friday 1-52: title and the email text (they have no video).
- Habits & Homework 1-26: one per week of the new trajectory, written (the app lists that week's new medals); video added later.
- Weeks 1-26 get their SBW (matched to the week, doc 27) and SMF 1-26.
The old XP questions are not imported: Michael approves new AI-drafted quizzes in the app.
"""
import re, sys, uuid
from pathlib import Path

NS = uuid.UUID("6f1c2b8e-1d2a-4f0e-9a51-6c2b7d9e0a13")
lid = lambda kind, n: str(uuid.uuid5(NS, f"lesson:{kind}:{n}"))
q = lambda s: "null" if s is None else "'" + s.replace("'", "''") + "'"

src = Path(sys.argv[1]).read_text()
# Only the week sections (the appendices repeat some headings).
src = src[: src.index("# Appendix A")]
sections = re.split(r"(?m)^## ", src)


def clean(text: str) -> str:
    text = re.sub(r"(?s)\*\*XP questions:\*\*.*", "", text)
    lines = [l.rstrip() for l in text.strip().splitlines()]
    out, blank = [], False
    for l in lines:
        if not l.strip():
            if not blank and out:
                out.append("")
            blank = True
            continue
        blank = False
        out.append(re.sub(r"^>\s?", "", l))
    return "\n".join(out).strip()


lessons = {}
for sec in sections:
    m = re.match(r"(Strong Body Wednesday|Strong Mind Friday) (\d+)\s*\n", sec)
    if not m:
        continue
    kind = "sbw" if m.group(1).startswith("Strong Body") else "smf"
    n = int(m.group(2))
    if (kind, n) in lessons:
        continue
    body = sec[m.end():]
    subj = re.search(r"\*\*Email — subject:\*\*\s*(.+)", body)
    title = subj.group(1).strip() if subj else ""
    title = re.sub(r"(?i)^strong (body wednesday|mind friday)\s*\d+\s*[-–:]\s*", "", title).strip()
    summary = re.search(r"\*\*Summary:\*\*\s*(.+)", body)
    if summary and summary.group(1).strip():
        title = summary.group(1).strip()
    video = re.search(r"\*\*Video:\*\*\s*(\S+)", body)
    notes = re.search(r"(?s)\*\*Notes:\*\*(.*?)(?=\*\*XP questions:\*\*|\Z)", body)
    email = re.search(r"(?s)\*\*Email — subject:\*\*[^\n]*\n(.*?)(?=\*\*Lesson:|\*\*XP questions:\*\*|\Z)", body)
    text = clean(notes.group(1)) if notes and len(clean(notes.group(1))) > 200 else clean(email.group(1) if email else "")
    title = title[:1].upper() + title[1:] if title else f"{m.group(1)} {n}"
    lessons[(kind, n)] = dict(title=title, video=video.group(1).strip() if video else None, body=text or None)

assert sum(1 for k in lessons if k[0] == "sbw") == 52, "expected 52 SBW"
assert sum(1 for k in lessons if k[0] == "smf") == 52, "expected 52 SMF"

# Doc 27: the SBW for each week of the new trajectory.
SBW_FOR_WEEK = [2, 6, 1, 43, 3, 17, 14, 8, 11, 46, 7, 37, 5, 9, 22, 13, 16, 44, 4, 18, 41, 32, 51, 50, 15, 12]

out = ["-- Weekly lessons in the app. Generated by scripts/build_lessons.py from doc 20. Safe to run more than once.", ""]
out += [
    "alter table public.lessons add column if not exists quiz jsonb;            -- [{q, options: [..], correct: 0}]",
    "alter table public.lessons add column if not exists quiz_status text not null default 'none' check (quiz_status in ('none','draft','approved'));",
    "alter table public.lessons add column if not exists week_number int;      -- the week of the 26-week trajectory it belongs to",
    "create unique index if not exists lessons_kind_number on public.lessons (kind, number);",
    "alter table public.trajectory_weeks add column if not exists hh_lesson_id uuid references public.lessons (id);",
    "",
    "-- What she has watched and which quizzes she passed.",
    "create table if not exists public.lesson_progress (",
    "  client_id uuid not null references public.profiles (id) on delete cascade,",
    "  lesson_id uuid not null references public.lessons (id) on delete cascade,",
    "  watched_at timestamptz,",
    "  quiz_passed_at timestamptz,",
    "  primary key (client_id, lesson_id)",
    ");",
    "alter table public.lesson_progress enable row level security;",
    "drop policy if exists \"own lesson progress\" on public.lesson_progress;",
    "create policy \"own lesson progress\" on public.lesson_progress for all",
    "  using (client_id = auth.uid() or public.is_coach()) with check (client_id = auth.uid());",
    "",
]
for (kind, n), l in sorted(lessons.items()):
    retired = kind == "sbw" and n == 39  # intermittent fasting: retired (doc 23)
    out.append(
        f"insert into public.lessons (id, kind, number, title, video_url, body, retired) values ({q(lid(kind, n))}, '{kind}', {n}, {q(l['title'])}, {q(l['video'])}, {q(l['body'])}, {str(retired).lower()})"
        f" on conflict (id) do update set title = excluded.title, video_url = coalesce(public.lessons.video_url, excluded.video_url), body = coalesce(public.lessons.body, excluded.body), retired = excluded.retired;"
    )
for w in range(1, 27):
    out.append(
        f"insert into public.lessons (id, kind, number, title, week_number) values ({q(lid('hh', w))}, 'hh', {w}, 'Week {w} Habits & Homework', {w}) on conflict (id) do nothing;"
    )
out.append("")
for w in range(1, 27):
    sbw = SBW_FOR_WEEK[w - 1]
    out.append(f"update public.lessons set week_number = {w} where id = {q(lid('sbw', sbw))};")
    out.append(f"update public.lessons set week_number = {w} where id = {q(lid('smf', w))};")
    out.append(
        f"update public.trajectory_weeks set hh_lesson_id = {q(lid('hh', w))}, sbw_lesson_id = {q(lid('sbw', sbw))}, smf_lesson_id = {q(lid('smf', w))} where week_number = {w};"
    )
Path(__file__).resolve().parent.parent.joinpath("supabase/migrations/0013_lessons.sql").write_text("\n".join(out) + "\n")
print(len(lessons), "lessons;", sum(1 for l in lessons.values() if l["video"]), "with video")
for k in [("sbw", 1), ("sbw", 2), ("smf", 1), ("smf", 26)]:
    l = lessons[k]
    print(k, "|", l["title"], "|", l["video"], "|", (l["body"] or "")[:90].replace("\n", " "), "| chars", len(l["body"] or ""))
