"""Builds supabase/migrations/0023_workouts.sql: workout tables + the Strong Life Transformation Program from Trainerize.

Source: scripts/data/sltp_trainerize.json (read from Trainerize on October 27, 2026) and scripts/data/sltp_clips.json
(the 356 clips saved from Trainerize; uploaded by Michael on Coach -> Exercise clips to exercise-clips/sltp/<id>.mp4).
"""
import json, datetime as dt
from pathlib import Path

ROOT = Path(__file__).resolve().parent
d = json.loads((ROOT / "data/sltp_trainerize.json").read_text())
clips = {c["id"] for c in json.loads((ROOT / "data/sltp_clips.json").read_text())}
q = lambda s: "null" if s is None or s == "" else "'" + str(s).replace("'", "''") + "'"
n = lambda v: "null" if v in (None, "") else str(v)

out = ["-- Workouts in the app (decided October 28). Generated by scripts/build_workouts.py. Safe to run more than once.", "", """
create table if not exists public.exercises (
  id bigint primary key,                 -- Trainerize exercise id
  name text not null,
  notes text,                            -- Michael's how-to
  youtube_id text,                       -- video on Michael's YouTube
  clip_path text,                        -- or a saved clip in storage: exercise-clips/<path>.mp4 (+ .jpg poster)
  updated_at timestamptz not null default now()
);
create table if not exists public.workouts (
  id bigint primary key,
  name text not null,
  kind text not null check (kind in ('strength','cardio')),
  circuit boolean not null default false,
  rounds int,
  minutes int,
  notes text
);
create table if not exists public.workout_items (
  workout_id bigint not null references public.workouts (id) on delete cascade,
  position int not null,
  exercise_id bigint not null references public.exercises (id),
  sets int not null default 1,
  target text,                           -- "6 Rep Max", "10 steps each leg per set"
  seconds int,                           -- timed items
  rest_seconds int,
  log_type text not null,                -- strength · endurance · timedStrength · general · cardio · timedLongerBetter · timedFasterBetter · rest
  primary key (workout_id, position)
);
create table if not exists public.program_phases (
  id bigint primary key,
  program text not null default 'sltp',
  position int not null,
  name text not null,                    -- "DWTP Phase 1"
  stage text not null,                   -- DWTP · SLTP · PSR · SLF
  kind text not null check (kind in ('build','deload','pivot','max')),
  weeks int not null,
  first_week int not null,               -- program week this phase starts
  unique (program, position)
);
create table if not exists public.phase_workouts (
  phase_id bigint not null references public.program_phases (id) on delete cascade,
  workout_id bigint not null references public.workouts (id) on delete cascade,
  day int,                               -- strength: Day 1, 2, 3, 4 · cardio: null (her menu)
  primary key (phase_id, workout_id)
);

-- What she did: one session per workout per program week, and every set she logged.
create table if not exists public.workout_sessions (
  id uuid primary key default gen_random_uuid(),
  client_id uuid not null references public.profiles (id) on delete cascade,
  workout_id bigint not null references public.workouts (id),
  program_week int not null default 0,
  started_at timestamptz not null default now(),
  completed_at timestamptz,
  unique (client_id, workout_id, program_week)
);
create table if not exists public.set_logs (
  session_id uuid not null references public.workout_sessions (id) on delete cascade,
  client_id uuid not null references public.profiles (id) on delete cascade,
  position int not null,
  set_no int not null,
  exercise_id bigint not null references public.exercises (id),
  weight numeric,
  reps int,
  seconds int,
  note text,
  done boolean not null default true,
  logged_at timestamptz not null default now(),
  primary key (session_id, position, set_no)
);
create index if not exists set_logs_exercise on public.set_logs (client_id, exercise_id, logged_at desc);

do $$
declare t text;
begin
  foreach t in array array['exercises','workouts','workout_items','program_phases','phase_workouts'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists "read" on public.%I', t);
    execute format('create policy "read" on public.%I for select using (auth.uid() is not null)', t);
    execute format('drop policy if exists "coach writes" on public.%I', t);
    execute format('create policy "coach writes" on public.%I for all using (public.is_coach()) with check (public.is_coach())', t);
  end loop;
  foreach t in array array['workout_sessions','set_logs'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists "own rows" on public.%I', t);
    execute format('create policy "own rows" on public.%I for all using (client_id = auth.uid() or public.is_coach()) with check (client_id = auth.uid())', t);
  end loop;
end $$;

-- Exercise clips: public to play (no client data in them), only the coach uploads.
insert into storage.buckets (id, name, public) values ('exercise-clips', 'exercise-clips', true)
  on conflict (id) do update set public = true;
drop policy if exists "clips readable" on storage.objects;
create policy "clips readable" on storage.objects for select using (bucket_id = 'exercise-clips');
drop policy if exists "coach uploads clips" on storage.objects;
create policy "coach uploads clips" on storage.objects for insert with check (bucket_id = 'exercise-clips' and public.is_coach());
drop policy if exists "coach updates clips" on storage.objects;
create policy "coach updates clips" on storage.objects for update using (bucket_id = 'exercise-clips' and public.is_coach());
drop policy if exists "coach deletes clips" on storage.objects;
create policy "coach deletes clips" on storage.objects for delete using (bucket_id = 'exercise-clips' and public.is_coach());
""".strip(), ""]

for k, e in sorted(d["exercises"].items(), key=lambda kv: int(kv[0])):
    v = e["video"] or ""
    yt = v if v and not v.startswith("awss3:") and ":" not in v else None
    clip = f"sltp/{k}" if int(k) in clips else None
    out.append(f"insert into public.exercises (id, name, notes, youtube_id, clip_path) values ({k}, {q(e['name'])}, {q((e['description'] or '').strip())}, {q(yt)}, {q(clip)}) "
               "on conflict (id) do update set name = excluded.name, notes = excluded.notes, youtube_id = excluded.youtube_id, clip_path = coalesce(public.exercises.clip_path, excluded.clip_path), updated_at = now();")
out.append("")
for k, w in sorted(d["workouts"].items(), key=lambda kv: int(kv[0])):
    kind = "cardio" if "Cardio" in w["name"] else "strength"
    mins = round(w["duration"] / 60) if w.get("duration") else None
    out.append(f"insert into public.workouts (id, name, kind, circuit, rounds, minutes, notes) values ({k}, {q(w['name'])}, '{kind}', {str(w['type'] == 'workoutCircuit').lower()}, {n(w.get('rounds'))}, {n(mins)}, {q(w.get('instruction'))}) "
               "on conflict (id) do update set name = excluded.name, kind = excluded.kind, circuit = excluded.circuit, rounds = excluded.rounds, minutes = excluded.minutes, notes = excluded.notes;")
    out.append(f"delete from public.workout_items where workout_id = {k};")
    rows = []
    for i, x in enumerate(w["exercises"], 1):
        td = x.get("td") or {}
        rows.append(f"({k}, {i}, {x['ex']}, {x['sets'] or 1}, {q(x['target'])}, {n(td.get('time'))}, {n(x['rest'] or None)}, {q(x['rec'])})")
    if rows:
        out.append("insert into public.workout_items (workout_id, position, exercise_id, sets, target, seconds, rest_seconds, log_type) values\n  " + ",\n  ".join(rows) + ";")
out.append("")

# Phases in program order, weeks from Trainerize's phase dates. Every phase gets the full cardio menu (decided October 28).
cardio = sorted(int(k) for k, w in d["workouts"].items() if "Cardio" in w["name"])
week = 1
for pos, p in enumerate(d["phases"], 1):
    weeks = ((dt.date.fromisoformat(p["end"]) - dt.date.fromisoformat(p["start"])).days + 1) // 7
    nm = p["name"].rstrip(".").strip()
    stage = nm.split()[0]
    kind = "deload" if "Deload" in nm else "pivot" if "Pivot" in nm else "max" if "Max" in nm else "build"
    out.append(f"insert into public.program_phases (id, program, position, name, stage, kind, weeks, first_week) values ({p['id']}, 'sltp', {pos}, {q(nm)}, '{stage}', '{kind}', {weeks}, {week}) "
               "on conflict (id) do update set position = excluded.position, name = excluded.name, stage = excluded.stage, kind = excluded.kind, weeks = excluded.weeks, first_week = excluded.first_week;")
    out.append(f"delete from public.phase_workouts where phase_id = {p['id']};")
    rows = []
    for wid in p["workouts"]:
        name = d["workouts"][str(wid)]["name"]
        if "Cardio" in name: continue
        day = int(name.rsplit("Day", 1)[1].strip()) if "Day" in name else None
        rows.append(f"({p['id']}, {wid}, {n(day)})")
    rows += [f"({p['id']}, {c}, null)" for c in cardio]
    out.append("insert into public.phase_workouts (phase_id, workout_id, day) values " + ", ".join(rows) + " on conflict do nothing;")
    week += weeks
out.append(f"\n-- {len(d['phases'])} phases, {week - 1} weeks, {len(d['workouts'])} workouts, {len(d['exercises'])} exercises.")
out.append("select (select count(*) from public.program_phases) phases, (select count(*) from public.workouts) workouts, (select count(*) from public.exercises) exercises, (select count(*) from public.exercises where clip_path is not null) clips;")
(ROOT.parent / "supabase/migrations/0023_workouts.sql").write_text("\n".join(out) + "\n")
print("weeks", week - 1, "bytes", sum(len(l) for l in out))
