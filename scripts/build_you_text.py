"""Build supabase/migrations/0009 part: rewrite program text from "she/her" to "you/your" (October 24).
Reads the seed, converts every value that mentions her, and writes exact-match updates."""
import re

s = open("supabase/seed/01_circles.sql", encoding="utf-8").read()

def medal(t):  # same as 0008: the database already says "medal"
    t = re.sub(r"\bRings\b", "Medals", t); t = re.sub(r"(?<!on )\brings\b", "medals", t)
    t = re.sub(r"\bRing\b", "Medal", t); return re.sub(r"\bring\b", "medal", t)

OVERRIDES = {
    "she sleeps 7.5 hours through the night on a steady rhythm, wakes with energy, has no 3 PM crash, and caffeine is optional.":
        "You sleep 7.5 hours through the night on a steady rhythm, wake with energy, have no 3 PM crash, and caffeine is optional.",
    "The moment she's been training for": "The moment you've been training for",
    "She sees what she really eats": "You see what you really eat",
}

def verb(v):
    if v == "has": return "have"
    if v.endswith("sses") or v.endswith("shes") or v.endswith("ches"): return v[:-2]
    if v.endswith("s") and not v.endswith("ss"): return v[:-1]
    return v

def you(t):
    if t in OVERRIDES: return OVERRIDES[t]
    t = re.sub(r"\bherself\b", "yourself", t); t = re.sub(r"\bHerself\b", "Yourself", t)
    t = re.sub(r"\bshe's been\b", "you've been", t)
    t = re.sub(r"\bshe's\b", "you're", t); t = re.sub(r"\bShe's\b", "You're", t)
    t = re.sub(r"\b(she|She) (can't|can|executed)\b", lambda m: ("you" if m.group(1) == "she" else "You") + " " + m.group(2), t)
    t = re.sub(r"\b(she|She) ([a-z]+)\b", lambda m: ("you" if m.group(1) == "she" else "You") + " " + verb(m.group(2)), t)
    # "her" as an object (end of phrase, or before at/in/up) → "you"; otherwise possessive → "your"
    t = re.sub(r"\bher(?=\s*($|[,.;:)]|\s(at|in|up)\b))", "you", t)
    t = re.sub(r"\bher\b", "your", t); t = re.sub(r"\bHer\b", "Your", t)
    return t

pairs = {}
for m in re.finditer(r"'((?:[^']|'')*)'", s):
    old = m.group(1).replace("''", "'")
    if re.search(r"\b(she|her|herself|She|Her)\b", old):
        pairs[medal(old)] = medal(you(old))

q = lambda x: "'" + x.replace("'", "''") + "'"
cols = [("ring_items", "title"), ("ring_items", "detail"), ("rings", "name"), ("rings", "outcome"),
        ("circles", "goal"), ("circles", "see_a_professional")]
out = ["-- Program text speaks to her: \"you/your\" instead of \"she/her\" (October 24). Generated by scripts/build_you_text.py."]
for old, new in sorted(pairs.items()):
    for t, c in cols:
        out.append(f"update public.{t} set {c} = {q(new)} where {c} = {q(old)};")
open("supabase/you_text.sql", "w", encoding="utf-8").write("\n".join(out) + "\n")
for old, new in sorted(pairs.items()):
    print(f"{old[:70]:72} → {new[:70]}")
