-- November 20 (Michael): undo and redo everywhere in the app (⌘Z / ⇧⌘Z, or the Undo button that pops up after a change).
-- Every change a signed-in person makes to these tables is written down (the row before and after). "Undo" puts back
-- that person's last step (everything they changed within 3 seconds of their last change); "Redo" does it again.
-- Kept for 2 days. Changes made by the app itself in the background (no one signed in) aren't recorded.

create table if not exists public.undo_log (
  id bigint generated by default as identity primary key,
  user_id uuid not null,
  tbl text not null,
  op text not null check (op in ('INSERT', 'UPDATE', 'DELETE')),
  old_row jsonb,
  new_row jsonb,
  undone boolean not null default false,
  undone_at timestamptz,
  created_at timestamptz not null default clock_timestamp()
);
create index if not exists undo_log_user on public.undo_log (user_id, id desc);
alter table public.undo_log enable row level security; -- nobody reads it directly; only the functions below

drop function if exists public.undo_apply(public.undo_log, boolean);

-- The trigger: write the change down (not while undoing or redoing, and only for a signed-in person).
create or replace function public.undo_record() returns trigger language plpgsql security definer set search_path = public as $$
declare uid uuid := auth.uid();
begin
  if uid is null or coalesce(current_setting('dwtp.undoing', true), '') = '1' then return null; end if;
  -- A new change after an undo: the old redo steps no longer apply.
  delete from public.undo_log where user_id = uid and undone;
  insert into public.undo_log (user_id, tbl, op, old_row, new_row)
  values (uid, tg_table_name, tg_op,
    case when tg_op in ('UPDATE', 'DELETE') then to_jsonb(old) end,
    case when tg_op in ('INSERT', 'UPDATE') then to_jsonb(new) end);
  return null;
end $$;

-- "col1 = r.col1 and …" for a table's primary key, comparing the table (t) with a row (r).
create or replace function public.undo_pk(t text) returns text language sql stable set search_path = public as $$
  select string_agg(format('t.%1$I is not distinct from r.%1$I', a.attname), ' and ')
  from pg_index i join pg_attribute a on a.attrelid = i.indrelid and a.attnum = any(i.indkey)
  where i.indrelid = ('public.' || quote_ident(t))::regclass and i.indisprimary
$$;

-- Put one row back the way it was (back = true: undo) or forward again (back = false: redo).
create or replace function public.undo_apply(e public.undo_log, back boolean) returns boolean language plpgsql security definer set search_path = public as $$
declare
  pk text := public.undo_pk(e.tbl);
  cols text;
  target jsonb;
  kind text;  -- what to do: remove, restore (insert or update to a row)
  n int;
begin
  if pk is null then return false; end if;
  if back then
    kind := case e.op when 'INSERT' then 'remove' else 'restore' end; target := coalesce(e.old_row, e.new_row);
  else
    kind := case e.op when 'DELETE' then 'remove' else 'restore' end; target := coalesce(e.new_row, e.old_row);
  end if;
  if kind = 'remove' then
    execute format('delete from public.%1$I t using jsonb_populate_record(null::public.%1$I, $1) r where %2$s', e.tbl, pk) using target;
  else
    select string_agg(format('%1$I = r.%1$I', a.attname), ', ') into cols
    from pg_attribute a where a.attrelid = ('public.' || quote_ident(e.tbl))::regclass and a.attnum > 0 and not a.attisdropped and a.attgenerated = '' and a.attidentity <> 'a';
    execute format('update public.%1$I t set %2$s from jsonb_populate_record(null::public.%1$I, $1) r where %3$s', e.tbl, cols, pk) using target;
    get diagnostics n = row_count; -- (EXECUTE doesn't set FOUND)
    if n = 0 then
      execute format('insert into public.%1$I overriding system value select * from jsonb_populate_record(null::public.%1$I, $1) on conflict do nothing', e.tbl) using target;
    end if;
  end if;
  return true;
exception when others then
  return false; -- a row that can't go back yet (its parent isn't back) is tried again after the others
end $$;

-- Undo her last step. Returns which tables changed (the app turns that into words), or nothing to undo.
create or replace function public.undo_last() returns jsonb language plpgsql security definer set search_path = public as $$
declare uid uuid := auth.uid(); top public.undo_log; e public.undo_log; tables text[] := '{}'; again public.undo_log[] := '{}';
begin
  if uid is null then return jsonb_build_object('ok', false); end if;
  delete from public.undo_log where created_at < now() - interval '2 days';
  select * into top from public.undo_log where user_id = uid and not undone order by id desc limit 1;
  if top.id is null then return jsonb_build_object('ok', false); end if;
  perform set_config('dwtp.undoing', '1', true);
  for e in select * from public.undo_log where user_id = uid and not undone and created_at >= top.created_at - interval '3 seconds' order by id desc loop
    if not public.undo_apply(e, true) then again := array_append(again, e); end if;
    tables := array_append(tables, e.tbl);
    update public.undo_log set undone = true, undone_at = clock_timestamp() where id = e.id;
  end loop;
  foreach e in array again loop perform public.undo_apply(e, true); end loop;
  return jsonb_build_object('ok', true, 'tables', to_jsonb(tables));
end $$;

-- Redo the last step she undid.
create or replace function public.redo_last() returns jsonb language plpgsql security definer set search_path = public as $$
declare uid uuid := auth.uid(); top public.undo_log; e public.undo_log; tables text[] := '{}'; again public.undo_log[] := '{}';
begin
  if uid is null then return jsonb_build_object('ok', false); end if;
  select * into top from public.undo_log where user_id = uid and undone order by undone_at desc, id asc limit 1;
  if top.id is null then return jsonb_build_object('ok', false); end if;
  perform set_config('dwtp.undoing', '1', true);
  for e in select * from public.undo_log where user_id = uid and undone and undone_at >= top.undone_at - interval '1 second' order by id asc loop
    if not public.undo_apply(e, false) then again := array_append(again, e); end if;
    tables := array_append(tables, e.tbl);
    update public.undo_log set undone = false, undone_at = null where id = e.id;
  end loop;
  foreach e in array again loop perform public.undo_apply(e, false); end loop;
  return jsonb_build_object('ok', true, 'tables', to_jsonb(tables));
end $$;

-- Her latest step that can be undone (0 if none), so the app knows to show its Undo button after a change.
create or replace function public.undo_peek() returns bigint language sql stable security definer set search_path = public as $$
  select coalesce(max(id), 0) from public.undo_log where user_id = auth.uid() and not undone
$$;

grant execute on function public.undo_peek() to authenticated;
grant execute on function public.undo_last() to authenticated;
grant execute on function public.redo_last() to authenticated;
revoke execute on function public.undo_apply(public.undo_log, boolean) from public, anon, authenticated;

