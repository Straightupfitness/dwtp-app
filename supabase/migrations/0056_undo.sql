    'leads', 'kpi_expenses', 'kpi_slots', 'kpi_clients', 'kpi_payments'] loop
    if to_regclass('public.' || t) is not null then
      execute format('drop trigger if exists undo_record on public.%I', t);
      execute format('create trigger undo_record after insert or update or delete on public.%I for each row execute function public.undo_record()', t);
    end if;
  end loop;
end $$;

